def 统计():
    """统计各类型数量"""
    类型计数: Dict[str, int] = {}
    for _, (_, 类型, _) in 统计锥.items():
        类型计数[类型] = 类型计数.get(类型, 0) + 1
    return 类型计数


def 获取名称(编号: int) -> str:
    """获取符号名称"""
    if 编号 in 统计锥:
        return 统计锥[编号][0]
    return f'通用({编号})'


def 获取描述(编号: int) -> str:
    """获取符号描述"""
    if 编号 in 统计锥:
        return 统计锥[编号][2]
    return f'未定义维度{编号}'


def 全部锥() -> List[Tuple[int, str, str, str]]:
    """返回所有统计锥"""
    return [(k, v[0], v[1], v[2]) for k, v in sorted(统计锥.items())]


